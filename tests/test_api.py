"""Automated contract and regression tests for the inference API."""
from fastapi.testclient import TestClient
from main import app, THRESHOLD

client = TestClient(app)

VALID_CUSTOMER = {
    "gender": "Female",
    "SeniorCitizen": 0,
    "Partner": "Yes",
    "Dependents": "No",
    "tenure": 1,
    "PhoneService": "No",
    "MultipleLines": "No phone service",
    "InternetService": "DSL",
    "OnlineSecurity": "No",
    "OnlineBackup": "Yes",
    "DeviceProtection": "No",
    "TechSupport": "No",
    "StreamingTV": "No",
    "StreamingMovies": "No",
    "Contract": "Month-to-month",
    "PaperlessBilling": "Yes",
    "PaymentMethod": "Electronic check",
    "MonthlyCharges": 29.85,
    "TotalCharges": 29.85,
}

def test_valid_input_returns_probability_and_label():
    response = client.post("/predict", json=VALID_CUSTOMER)
    assert response.status_code == 200
    body = response.json()
    assert 0 <= body["churn_probability"] <= 1
    assert body["prediction"] in {"Yes", "No"}
    assert body["threshold"] == THRESHOLD

def test_missing_required_field_is_rejected():
    payload = VALID_CUSTOMER.copy()
    payload.pop("tenure")
    response = client.post("/predict", json=payload)
    assert response.status_code == 422

def test_invalid_data_type_is_rejected():
    payload = VALID_CUSTOMER.copy()
    payload["MonthlyCharges"] = "not-a-number"
    response = client.post("/predict", json=payload)
    assert response.status_code == 422

def test_out_of_range_value_is_rejected():
    payload = VALID_CUSTOMER.copy()
    payload["tenure"] = 100
    response = client.post("/predict", json=payload)
    assert response.status_code == 422

def test_unseen_category_is_handled_without_crashing():
    payload = VALID_CUSTOMER.copy()
    payload["PaymentMethod"] = "New payment method"
    response = client.post("/predict", json=payload)
    assert response.status_code == 200
    assert 0 <= response.json()["churn_probability"] <= 1

def test_known_input_regression_probability():
    response = client.post("/predict", json=VALID_CUSTOMER)
    assert response.status_code == 200
    # Probability generated by the frozen Week 7 model artifact.
    assert abs(response.json()["churn_probability"] - 0.66261) < 0.00002
    assert response.json()["prediction"] == "Yes"
